"""README.md, generated from profile.toml: a header, a few lines of real
Markdown, then projects, stack and stats, and the links that are filled in."""

from __future__ import annotations

import hashlib
from pathlib import Path

from . import stats_card
from .svg import esc

ASSETS = Path(__file__).resolve().parent.parent / "assets"


def versioned(name: str, assets: Path = ASSETS) -> str:
    """URL of a card with a short hash of its content, so GitHub's image
    cache never serves an old version after a refresh."""
    digest = hashlib.sha256((assets / name).read_bytes()).hexdigest()[:10]
    return f"assets/{name}?v={digest}"


def picture(name: str, alt: str, width: str) -> str:
    dark, light = versioned(f"{name}-dark.svg"), versioned(f"{name}-light.svg")
    return (f'<picture>\n'
            f'  <source media="(prefers-color-scheme: dark)" srcset="{dark}">\n'
            f'  <source media="(prefers-color-scheme: light)" srcset="{light}">\n'
            f'  <img alt="{esc(alt)}" src="{light}" width="{width}">\n'
            f'</picture>')


def links(cfg: dict, labels: dict) -> list[str]:
    """Only the links filled in profile.toml; nothing is ever made up."""
    contact, names = cfg.get("contact", {}), labels["readme"]["links"]
    out = []
    email = contact.get("email", "").strip()
    if email:
        out.append(f'<a href="mailto:{esc(email)}">{esc(names["email"])}</a>')
    for key in ("linkedin", "website"):
        url = contact.get(key, "").strip()
        if url:
            out.append(f'<a href="{esc(url)}">{esc(names[key])}</a>')
    return out


def centred(tag: str, content: str) -> str:
    return f'<{tag} align="center">{content}</{tag}>'


def readme(ctx) -> str:
    cfg, lab = ctx.cfg, ctx.labels
    # One centred column: the cards are 480 px wide so that no text drops
    # under 11 px on a 375 px phone.
    parts = [
        "<!-- Generated by `python3 -m profilegen` from profile.toml. Edit that file, not this one. -->",
        picture("header", lab["readme"]["alt_header"], "100%"),
        centred("p", esc(lab["intro"])),
        centred("h3", esc(lab["projects_title"])),
        centred("p", picture("projects", lab["readme"]["alt_projects"], "480")),
        centred("h3", esc(lab["stack_title"])),
        centred("p", picture("stack", lab["readme"]["alt_stack"], "480") + "<br>\n<sub>"
                + " · ".join(esc(i["name"]) for i in lab["stack"]) + "</sub>"),
        centred("h3", esc(lab["stats"]["title"])),
        centred("p", picture("stats", stats_card.summary(ctx), "480")),
    ]
    footer = links(cfg, lab)
    if footer:
        parts.append(centred("p", " · ".join(footer)))
    return "\n\n".join(parts) + "\n"
